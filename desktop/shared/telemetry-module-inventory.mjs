const MODULE_SET_BY_COMPONENT = new Map(
  Object.entries(APPROVED_TELEMETRY_MODULES)
    .map(([component, modules]) => [component, new Set(modules)]),
);

export function isApprovedTelemetryModule(component, module) {
  return typeof module === "string" && MODULE_SET_BY_COMPONENT.get(component)?.has(module) === true;
}
