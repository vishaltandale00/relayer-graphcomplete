import { Window } from 'happy-dom';
import { afterEach, expect, it, vi } from 'vitest';
import { createProductWorkspace } from '../desktop/renderer/src/product-workspace/workspace.js';
import { taskActorCurrentIdentity, taskActorCurrentUnchanged, taskActorControlIdentity, taskActorRebindControl, taskActorWorkingControlAllowed } from '../desktop/eval-main/task-actor-browser.mjs';
afterEach(() => vi.unstubAllGlobals());
it('paints an explicit latest-update control, keeps the historical view and composer draft, and retires foreign updates', async () => {
  const w = new Window({ url: 'http://127.0.0.1:3000' });
  vi.stubGlobal('document', w.document);
  vi.stubGlobal('window', w);
  vi.stubGlobal('lucide', new Proxy({ Circle: {}, createElement: () => w.document.createElement('svg') }, { get: (t, k) => t[k] ?? {} }));
  w.document.body.innerHTML = '<section id="threadView"></section><div id="toast" class="hidden"></div>';
  const node = { id: 53, title: 'Earlier comparison', detail: 'Old options', state: 'accepted' };
  const layer = { layer: { id: 19, state: 'accepted' }, nodes: [node], actions: [], edges: [] };
  const turn = { id: 5, threadId: 3, graphNodeId: 50, completionStatus: 'running', latestAttempt: { id: 5 }, text: 'Plan a trip', contexts: [] };
  const thread = { id: 3, harnessId: 'fixture' };
  const projection = { completionId: 50, headRevision: 2, currentLayerId: 20, temporalFeatures: { projectionUi: true } };
  const state = { status: 'running', currentInteractionId: 5, interactions: [turn], visibleLayer: layer, nodes: [node], edges: [], actions: [], projects: [], permissionProfiles: [], modelSettings: { defaults: { harnessId: 'fixture' }, harnesses: [{ id: 'fixture', available: true }], providers: [], families: [] }, modelCatalog: [], actionInvocations: [], pendingActionInvocations: [], currentProjections: new Map([['50', projection]]) };
  const selection = { currentThreadId: 3, currentInteractionId: 5, selectedNodeId: null, nodeDetailsClosed: true, layerPath: [{ layerId: 18, label: 'Original update' }, { layerId: 19, label: 'Comparison' }], temporalCurrent: { completionId: 50, revision: 2, pinnedAtRevision: 1, mode: 'pinned' } };
  let finishNavigation;
  const open = vi.fn(() => new Promise(resolve => { finishNavigation = resolve; }));
  const ws = createProductWorkspace({ root: w.document, getState: () => state, getThread: () => thread, selection, onOpenLatestCurrent: open, showThread() { }, showEmpty() { } });
  try {
    ws.render();
    const draft = w.document.querySelector('#threadPrompt');
    draft.value = 'Unsent clarification';
    const cue = w.document.querySelector('#viewLatestUpdate');
    expect(cue.textContent).toContain('New update available');
    expect(cue.getAttribute('aria-label')).toBe('View latest update');
    expect(state.visibleLayer.layer.id).toBe(19);
    cue.click();
    await vi.waitFor(() => expect(open).toHaveBeenCalledOnce());
    expect(open.mock.calls[0][0]).toMatchObject({ threadId: 3, turnId: 5, attemptId: 5, completionId: 50, revision: 2, layerId: 20 });
    const breadcrumb = w.document.querySelector('#workspaceBreadcrumb');
    expect(breadcrumb.getAttribute('aria-busy')).toBe('true');
    ws.render();
    expect(draft.value).toBe('Unsent clarification');
    expect(breadcrumb.getAttribute('aria-busy')).toBe('true');
    finishNavigation();
    await vi.waitFor(() => expect(breadcrumb.hasAttribute('aria-busy')).toBe(false));
    open.mockRejectedValueOnce(new Error('Layer read failed'));
    w.document.querySelector('#viewLatestUpdate').click();
    await vi.waitFor(() => expect(w.document.querySelector('#toast').textContent).toBe('Layer read failed'));
    expect(breadcrumb.hasAttribute('aria-busy')).toBe(false);
    delete selection.temporalCurrent.pinnedAtRevision;
    ws.render();
    expect(w.document.querySelector('#viewLatestUpdate').textContent).toBe('View latest update');
    projection.completionId = 99;
    state.currentProjections = new Map([['99', projection]]);
    ws.render();
    expect(w.document.querySelector('#viewLatestUpdate')).toBeNull();
  }
  finally {
    ws.dispose();
    w.happyDOM.abort();
  }
});
it('new actor observes historical pixels and a visible scoped cue without granting legacy actors hidden Current knowledge', () => {
  const w = new Window({ width: 1480, height: 920 });
  w.document.body.innerHTML = '<div class="workspace-layout"><nav id="workspaceBreadcrumb"><button id="viewLatestUpdate" aria-label="View latest update" data-current-update-scope="[3,5,50,5]" data-current-update-revision="2">New update available · View latest update</button></nav></div>';
  const cue = w.document.querySelector('button');
  cue.getBoundingClientRect = () => ({ left: 10, top: 10, width: 250, height: 30 });
  w.document.elementFromPoint = () => cue;
  const expected = { threadId: 3, turnId: 5, attemptId: 5, submittedAt: 100 };
  const presentation = { threadId: 3, turnId: 5, attemptId: 5, observedAt: 200, graphVisible: true, completionStatus: 'running', layerId: 19, selectedNodeId: 53, navigationPath: [{ layerId: 18 }, { layerId: 19 }], currentPointer: { mode: 'pinned', revision: 2, layerId: 20 } };
  w.__taskActorPresentation = presentation;
  expect(taskActorCurrentIdentity({ expected, presentation, document: w.document })).toBeNull();
  const capture = () => taskActorCurrentIdentity({ expected, presentation, document: w.document, pinnedObservation: true });
  const first = capture();
  const host = w.document.createElement('section');
  w.document.querySelector('.workspace-layout').append(host);
  const authored = host.attachShadow({ mode: 'open' });
  authored.innerHTML = '<div class="workspace-layout"><nav id="workspaceBreadcrumb"><button id="viewLatestUpdate" data-current-update-revision="999">Authored invoke with colliding ID</button></nav></div>';
  const impostor = authored.querySelector('button');
  impostor.getBoundingClientRect = cue.getBoundingClientRect;
  authored.elementFromPoint = () => impostor;
  expect(taskActorWorkingControlAllowed(impostor, 'click')).toBe(false);
  expect(taskActorControlIdentity(impostor)).toBeNull();
  const capturedWithCollision = capture();
  impostor.dataset.currentUpdateRevision = '1000';
  expect(taskActorCurrentUnchanged(capture(), capturedWithCollision)).toBe(true);
  expect(first).toMatchObject({ viewingCurrent: false, layerId: 19, revision: 2 });
  presentation.observedAt++;
  expect(taskActorCurrentUnchanged(capture(), first)).toBe(true);
  presentation.currentPointer.revision = 3;
  expect(taskActorCurrentUnchanged(capture(), first)).toBe(true);
  cue.dataset.currentUpdateRevision = '3';
  expect(taskActorCurrentUnchanged(capture(), first)).toBe(false);
  expect(taskActorWorkingControlAllowed(cue, 'click')).toBe(true);
  const identity = taskActorControlIdentity(cue);
  expect(identity.kind).toBe('current-update');
  cue.remove();
  expect(taskActorRebindControl(identity, w.document)).toBeNull();
  w.document.querySelector('#workspaceBreadcrumb').append(cue);
  expect(taskActorRebindControl(identity, w.document)).toBe(cue);
  cue.dataset.currentUpdateScope = '[3,5,50,6]';
  expect(taskActorRebindControl(identity, w.document)).toBeNull();
  presentation.currentPointer = { mode: 'following', revision: 3, layerId: 20 };
  presentation.layerId = 20;
  expect(capture()).toMatchObject({ viewingCurrent: true, layerId: 20 });
  w.happyDOM.abort();
});
